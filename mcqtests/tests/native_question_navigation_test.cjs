'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ids = ['simpleDesc','calcQDesc','matchQDesc','numericalQDesc','shortansQDesc','categoryDesc','adddescriptionDesc','RSA','SCQ'];
const nodes = Object.fromEntries(ids.map(id => [id, {hidden:false,style:{},draft:'retained'}]));
let change, ready;
nodes.existingQ={value:'numericalQ',addEventListener:(event,fn)=>{change=fn;}};
const context={document:{getElementById:id=>nodes[id]||null,addEventListener:(_event,fn)=>{ready=fn;}},window:{location:{href:''}},numericalqUrl:'/numerical',mcqUrl:'/mcq'};
vm.runInNewContext(fs.readFileSync(__dirname+'/../resources/js/view.js','utf8'), context);
ready();
assert.equal(nodes.numericalQDesc.hidden,false);
assert.equal(nodes.simpleDesc.hidden,true);
nodes.existingQ.value='mcq';change();
assert.equal(nodes.simpleDesc.hidden,false);
assert.equal(nodes.numericalQDesc.hidden,true);
assert.equal(nodes.numericalQDesc.draft,'retained');
context.goAddQuestion();assert.equal(context.window.location.href,'/mcq');
nodes.existingQ.value='-';change();assert(ids.every(id=>nodes[id].hidden));
context.goAddQuestion();assert.equal(context.window.location.href,'/mcq');
delete nodes.calcQDesc;context.hideAll();
console.log('PASS native question navigation, placeholder reset, retained content and absent panels');
